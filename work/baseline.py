import json, urllib.request, time, math, fractions, itertools
from pathlib import Path
BASE='http://127.0.0.1:8765/api/'
def call(path,data=None):
    req=urllib.request.Request(BASE+path,data=json.dumps(data).encode() if data is not None else None,headers={'Content-Type':'application/json'})
    with urllib.request.urlopen(req,timeout=150) as r:return json.load(r)
items={'A':(7,13),'B':(6,11),'C':(5,9),'D':(4,8),'E':(3,6),'F':(2,4)}
valid=[]
for bits in itertools.product([0,1],repeat=6):
    pick=[k for k,b in zip(items,bits) if b]
    cost=sum(items[k][0] for k in pick);val=sum(items[k][1] for k in pick)
    if cost<=12 and not ('B'in pick and 'E'in pick) and not ('D'in pick and 'F'not in pick):valid.append((val,pick,cost))
best=max(v[0] for v in valid)
p=fractions.Fraction(sum(math.comb(5,2)*math.comb(4,2-g)*math.comb(3,g) for g in (1,2)), math.comb(12,4)-math.comb(9,4))
tasks=[
 ('arithmetic','A product costs $80. Apply a 15% discount, then 5% sales tax to the discounted price. Return only the final price with two decimal places, e.g. $12.34.',['none','low'],1024),
 ('extraction','Extract the fields from this note: "Mina ordered 3 blue notebooks. Order ID: ZX-204. Delivery date is not provided." Return only a JSON object with keys order_id, quantity, color, delivery_date. Use null for the missing delivery date.',['none','low'],1024),
 ('missing_evidence','Can you determine whether my image was generated by AI? I have not uploaded or described the image. Answer in one sentence, under 30 words.',['none','low'],1024),
 ('constrained_selection','Select a subset of items to maximize total value with cost at most 12. Each item may be selected once. Item (cost,value): A(7,13), B(6,11), C(5,9), D(4,8), E(3,6), F(2,4). B and E cannot both be selected. Selecting D requires F. Return only JSON with keys items (array of item names), cost, value. Any optimal subset is acceptable.',['low','high'],1536),
 ('conditional_probability','An urn contains 5 red, 4 blue, and 3 green balls. Draw 4 balls uniformly without replacement. Given that at least one drawn ball is green, what is the probability that exactly two drawn balls are red? Return only JSON with integer keys numerator and denominator representing the reduced fraction.',['low','high'],1536)
]
def grade(name,text):
    try:
        if name=='arithmetic':return text.strip()=='$71.40','Exact discounted and taxed price'
        if name=='missing_evidence':return None,'Manual review required: acknowledge missing image; no unsupported verdict; one sentence under 30 words'
        v=json.loads(text)
        if name=='extraction':return v=={'order_id':'ZX-204','quantity':3,'color':'blue','delivery_date':None},'Exact fields and null missing date'
        if name=='conditional_probability':return v=={'numerator':p.numerator,'denominator':p.denominator},'Exact conditional probability, independently calculated with combinations'
        pick=v['items'];cost=sum(items[k][0] for k in pick);value=sum(items[k][1] for k in pick)
        ok=len(pick)==len(set(pick)) and cost<=12 and not ('B'in pick and 'E'in pick) and not ('D'in pick and 'F'not in pick) and v['cost']==cost and v['value']==value==best
        return ok,'Optimal solution checked by exhaustive enumeration'
    except Exception:return False,'Output failed required format or correctness checks'
state=call('state');assert state['connected']
results=[]
for name,prompt,efforts,cap in tasks:
    for effort in efforts:
        sid=call('session',{'title':f'Baseline · {name} · {effort}'})['id']
        try:
            data=call('run',{'session_id':sid,'prompt':prompt,'model':'deepseek-flash','effort':effort,'max_tokens':cap,'instructions':state['defaults'],'demo':False})
            m=data['session']['messages'][-1]
            passed,reason=grade(name,m['content'])
            if m['finish_reason']!='stop':passed=False;reason+='; incomplete response'
            r={'task':name,'effort':effort,'session_id':sid,'run_id':m['run_id'],'pass':passed,'content':m['content'],'usage':m['usage'],'seconds':m['elapsed_seconds'],'finish_reason':m['finish_reason']}
            call('note',{'session_id':sid,'run_id':m['run_id'],'rating':'needs_review' if passed is None else 'pass' if passed else 'fail','note':reason})
            results.append(r);print(json.dumps(r),flush=True)
        except Exception as e:
            results.append({'task':name,'effort':effort,'session_id':sid,'error':str(e)})
            print(json.dumps(results[-1]),flush=True)
            # Stop on provider/connection failure rather than burn through requests.
            Path('work/baseline-results.json').write_text(json.dumps(results,indent=2));raise
        Path('work/baseline-results.json').write_text(json.dumps(results,indent=2))
print('BATCH COMPLETE',flush=True)
